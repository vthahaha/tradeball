// Flamin' Hot: each 2025-26 team's single best regular-season game by a player in the set.
// Writes hot.json, read by emit.js.
const fs = require("fs");
const path = require("path");
const D = path.join(__dirname, "data");
const stats = JSON.parse(fs.readFileSync(path.join(D, "stats2026.json"), "utf8"));
const sel = JSON.parse(fs.readFileSync(path.join(__dirname, "selection.json"), "utf8"));
const inSet = new Set([...sel.players, ...sel.rookies].map((p) => p.id));
const teamOf = Object.fromEntries(
  stats.athletes.map((a) => [a.athlete.id, a.athlete.teamShortName || a.athlete.teams?.[0]?.abbreviation]),
);
const nameOf = Object.fromEntries(stats.athletes.map((a) => [a.athlete.id, a.athlete.displayName]));

const games = [];
for (const f of fs.readdirSync(path.join(D, "gamelogs"))) {
  const id = f.replace(".json", "");
  const j = JSON.parse(fs.readFileSync(path.join(D, "gamelogs", f), "utf8"));
  const idx = Object.fromEntries((j.names || j.labels).map((n, i) => [n, i]));
  const L = Object.fromEntries(j.labels.map((n, i) => [n, i]));
  for (const st of j.seasonTypes || []) {
    if (!/Regular Season/i.test(st.displayName)) continue;
    for (const cat of st.categories || []) {
      for (const ev of cat.events || []) {
        const s = ev.stats;
        const num = (k) => Number(s[L[k]]) || 0;
        const [fgm, fga] = (s[L["FG"]] || "0-0").split("-").map(Number);
        const pts = num("PTS"), reb = num("REB"), ast = num("AST"), stl = num("STL"), blk = num("BLK"), to = num("TO");
        const e = j.events[ev.eventId] || {};
        games.push({
          id,
          name: nameOf[id],
          team: teamOf[id],
          pts, reb, ast, stl, blk, to,
          fg: fga ? Math.round((fgm / fga) * 1000) / 10 : 0,
          tp: Number(s[L["3P%"]]) || 0,
          opp: e.opponent?.abbreviation || e.opponent?.displayName || "",
          home: e.atVs === "vs",
          date: e.gameDate || "",
          score: pts + 0.7 * reb + 0.9 * ast + 1.5 * (stl + blk) - 0.7 * to,
        });
        void idx;
      }
    }
  }
}

const best = {};
for (const g of games) {
  if (!g.team || !inSet.has(g.id)) continue;
  if (!best[g.team] || g.score > best[g.team].score) best[g.team] = g;
}
const list = Object.values(best).sort((a, b) => b.score - a.score);
fs.writeFileSync(path.join(__dirname, "hot.json"), JSON.stringify(list, null, 1));
console.log("teams:", list.length);
for (const g of list) {
  const line = [`${g.pts} PTS`, g.reb >= 10 ? `${g.reb} REB` : null, g.ast >= 10 ? `${g.ast} AST` : null].filter(Boolean).join(" · ");
  console.log(`${g.team.padEnd(4)} ${g.name.padEnd(26)} ${line.padEnd(24)} ${g.home ? "vs" : "@"} ${g.opp} ${g.date.slice(0, 10)}`);
}

// Emit src/lib/catalog/nba-hot.ts
const OUT = path.join(__dirname, "..", "..", "src", "lib", "catalog", "nba-hot.ts");
const r1 = (x) => Math.round(x * 10) / 10;
const rows = list.map((g) => ({
  id: g.id,
  team: g.team,
  opp: g.opp,
  home: g.home,
  date: g.date.slice(0, 10),
  stats: { PTS: g.pts, REB: g.reb, AST: g.ast, STL: g.stl, BLK: g.blk, "FG%": r1(g.fg) },
}));
fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/nba/hot.js: each team's best 2025-26 regular-season game
// (points-led game score) by a player in the set. One card per 2025-26 team.
import type { HotGameRow } from "./types";

export const HOT_GAMES: HotGameRow[] = [
${rows.map((r) => "  " + JSON.stringify(r)).join(",\n")},
];
`,
);
console.log("wrote", OUT);
